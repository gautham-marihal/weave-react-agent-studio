// Builds the banking gateway into one browser file for Sandbox: src/sandbox/banking/gatewayInBrowser.js.
//   npm run sandbox:gateway        (run it again whenever services/banking-gateway changes)
// The gateway's own code goes in unchanged; only Node's http, crypto and Buffer are swapped for small browser
// stand-ins (scripts/sandbox-gateway/shims.mjs). esbuild comes with Vite.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const shims = fileURLToPath(new URL('./sandbox-gateway/shims.mjs', import.meta.url));
const outfile = `${root}src/sandbox/banking/gatewayInBrowser.js`;

const nodeInBrowser = {
  name: 'node-in-browser',
  setup(b) {
    // node:http: the gateway only needs createServer(handler) to give back something that can emit('request')
    b.onResolve({ filter: /^node:http$/ }, () => ({ path: 'node-http', namespace: 'browser-shim' }));
    b.onLoad({ filter: /^node-http$/, namespace: 'browser-shim' }, () => ({
      contents: `export function createServer(handler) {
  const on = new Map();
  return {
    emit(event, ...args) { if (event === 'request') return void handler(...args); (on.get(event) ?? []).forEach((fn) => fn(...args)); },
    on(event, fn) { on.set(event, [...(on.get(event) ?? []), fn]); return this; },
    listen() { return this; },
    close() { (on.get('close') ?? []).forEach((fn) => fn()); },
  };
}`,
      loader: 'js',
    }));
    b.onResolve({ filter: /^node:crypto$/ }, () => ({ path: shims }));
  },
};

await build({
  entryPoints: [fileURLToPath(new URL('./sandbox-gateway/entry.ts', import.meta.url))],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  outfile,
  plugins: [nodeInBrowser],
  // the gateway's Buffer, setInterval and clearInterval become the browser stand-ins
  inject: [shims],
  banner: {
    js: [
      '// GENERATED by scripts/build-sandbox-gateway.mjs from services/banking-gateway (its server routes, rehearsal routes',
      '// and mock bank) for Sandbox. Do not edit by hand: change the gateway, then run `npm run sandbox:gateway`.',
      '/* eslint-disable */',
      '// @ts-nocheck',
    ].join('\n'),
  },
  logLevel: 'warning',
});
console.log(`built ${outfile}`);
